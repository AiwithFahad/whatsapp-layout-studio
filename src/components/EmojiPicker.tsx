interface EmojiPickerProps {
  onSelect: (emoji: string) => void;
  onClose: () => void;
}

const EmojiPicker = ({ onSelect, onClose }: EmojiPickerProps) => {
  const [activeCategory, setActiveCategory] = useState("Smileys");
  const [search, setSearch] = useState("");
  const categoryKeys = Object.keys(EMOJI_CATEGORIES) as (keyof typeof EMOJI_CATEGORIES)[];

  const filteredEmojis = search
    ? Object.values(EMOJI_CATEGORIES).flat().filter(() => true) // show all when searching (emoji search is complex)
    : EMOJI_CATEGORIES[activeCategory as keyof typeof EMOJI_CATEGORIES] || [];

  return (
    <div className="absolute bottom-full left-0 mb-2 w-[320px] bg-card rounded-2xl gs-card-shadow border border-border overflow-hidden z-50 animate-fade-in">
      {/* Search */}
      <div className="p-3 border-b border-border">
        <input
          type="text"
          placeholder="Search emoji..."
          className="w-full bg-gs-search rounded-lg px-3 py-2 text-sm text-gs-text-primary placeholder:text-gs-text-secondary outline-none"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          autoFocus
        />
      </div>

      {/* Category tabs */}
      {!search && (
        <div className="flex gap-1 px-3 py-2 border-b border-border overflow-x-auto scrollbar-thin">
          {categoryKeys.map((cat) => (
            <button
              key={cat}
              onClick={() => setActiveCategory(cat)}
              className={`px-2.5 py-1 text-[11px] font-semibold rounded-full whitespace-nowrap transition-colors ${
                activeCategory === cat
                  ? "bg-gs-green text-primary-foreground"
                  : "text-gs-text-secondary hover:bg-gs-hover"
              }`}
            >
              {cat}
            </button>
          ))}
        </div>
      )}

      {/* Emoji grid */}
      <div className="grid grid-cols-8 gap-0.5 p-3 max-h-[220px] overflow-y-auto scrollbar-thin">
        {filteredEmojis.map((emoji, i) => (
          <button
            key={`${emoji}-${i}`}
            onClick={() => { onSelect(emoji); onClose(); }}
            className="w-9 h-9 flex items-center justify-center text-xl rounded-lg hover:bg-gs-hover transition-colors"
          >
            {emoji}
          </button>
        ))}
      </div>
    </div>
  );
};

export default EmojiPicker;
